/** Title for the current location; flow detail and admin pages share the leaderboard's. */
export function titleForPath(pathname: string): string {
  const path = pathname.length > 1 ? pathname.replace(/\/+$/, "") : pathname;
  const match = SITE_ROUTES.find((route) => route.path === path) ?? (path.startsWith("/flows/") ? SITE_ROUTES.find((route) => route.path === "/flows") : undefined);
  return (match ?? SITE_ROUTES[0]).title;
}

/**
 * Cloudflare Pages _redirects. Old and short URLs get a permanent redirect
 * (instead of a 404 then a client-side redirect), and flow detail pages are
 * served the leaderboard shell with a 200 (there is one per submitted flow, so
 * they can't be prerendered).
 */
export function buildRedirects(wikiSlugs: { id: string; slug: string }[]): string {
  const lines = [
    "# Generated by vite.config.ts (src/seo/routes.ts). Edit there, not in dist/.",
    "/calculator / 301",
    "/recipes https://skyshards.com/recipes 301",
    "/shards https://skyshards.com/shards 301",
  ];
  // Short links: /gloomgourd and /all_in_aloe -> /wiki/<slug>. Other spellings
  // still resolve in the app (ShortLinkRedirect).
  for (const { id, slug } of wikiSlugs) {
    lines.push(`/${slug} /wiki/${slug} 301`);
    if (id !== slug) lines.push(`/${id} /wiki/${slug} 301`);
  }
  // Dynamic rules must come after the static ones.
  lines.push("/flows/* /flows 200");
  return `${lines.join("\n")}\n`;
}
