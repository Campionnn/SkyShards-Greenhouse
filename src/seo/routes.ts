// have before the app loads. This is the one source for:
//   - document.title while the app runs (usePageTitle),
//   - the build-time dist/<route>.html files (vite.config.ts), which Cloudflare
//     Pages serves with a 200 at /<route>. Without them every deep link falls
//     through to 404.html: a 404 for Search Console, and a generic title and
//     canonical URL for Analytics and link previews.
//
// Pure (no DOM, no React): vite.config.ts imports it.

