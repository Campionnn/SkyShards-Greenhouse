// Bundles the share-image renderer (src/share/render-entry.ts + src/utilities/layoutImage.ts +
// designEncoding) into dist-share/share-render.mjs, plus the assets it draws with (crop icons, ground
// textures, Inter, data.json). SkyShards-API runs it as a long-lived Node worker for Discord embeds
// (utils/image_generator.py), so share images need no browser. @napi-rs/canvas stays external: the
// API installs it next to the bundle (tools/share-render/package.json).
//
// RENDER_VERSION hashes every bundled source and asset, so a change to the picture gives a new
// version and the API drops share images cached by an older renderer.
//
// Usage: pnpm build:share   (then pnpm sync:share to copy it into ../SkyShards-API/tools/share-render)

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(repoRoot, "src/share/render-entry.ts");
const outDir = resolve(repoRoot, "dist-share");
const outFile = resolve(outDir, "share-render.mjs");
const assets = [
  ["public/greenhouse/crops", "crops"],
  ["public/greenhouse/ground", "ground"],
  ["public/brand", "brand"],
  ["src/share/fonts", "fonts"],
];
const common = { entryPoints: [entry], bundle: true, platform: "node", format: "esm", target: "node20", external: ["@napi-rs/canvas"], logLevel: "silent" };

const probe = await build({ ...common, write: false, metafile: true, define: { __RENDER_VERSION__: '"probe"' } });
const hash = createHash("sha256");
for (const file of Object.keys(probe.metafile.inputs).sort()) {
  hash.update(file + "\0");
  hash.update(readFileSync(resolve(repoRoot, file)));
}
const files = [["public/greenhouse/data.json"]];
for (const [src] of assets) for (const f of readdirSync(resolve(repoRoot, src)).sort()) files.push([`${src}/${f}`]);
for (const [f] of files) {
  hash.update(f + "\0");
  hash.update(readFileSync(resolve(repoRoot, f)));
}
const version = hash.digest("hex").slice(0, 16);

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
const result = await build({
  ...common,
  outfile: outFile,
  logLevel: "warning",
  legalComments: "none",
  define: { __RENDER_VERSION__: JSON.stringify(version) },
  banner: { js: `// SkyShards share-image renderer. Generated by scripts/build-share-render.mjs; do not edit.\n// Render version ${version} (${new Date().toISOString()}).` },
});
if (result.errors.length) process.exit(1);

for (const [src, dst] of assets) cpSync(resolve(repoRoot, src), resolve(outDir, dst), { recursive: true });
cpSync(resolve(repoRoot, "public/greenhouse/data.json"), resolve(outDir, "data.json"));
const canvasVersion = JSON.parse(readFileSync(resolve(repoRoot, "node_modules/@napi-rs/canvas/package.json"), "utf8")).version;
writeFileSync(
  resolve(outDir, "package.json"),
  JSON.stringify({ name: "skyshards-share-render", private: true, type: "module", dependencies: { "@napi-rs/canvas": canvasVersion } }, null, 2) + "\n",
);
writeFileSync(resolve(outDir, "RENDER_VERSION"), version + "\n");
const size = readFileSync(outFile).length;
console.log(`build-share-render: ${relative(repoRoot, outFile)} (${(size / 1024).toFixed(0)} KB, render ${version}, @napi-rs/canvas ${canvasVersion})`);
