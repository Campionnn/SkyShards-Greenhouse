// Bundles the leaderboard verifier (src/leaderboard/verify-entry.ts + the whole simulator engine +
// public/greenhouse/data.json) into one self-contained Node script, dist-verify/verify.mjs, that
// the SkyShards API runs as a subprocess. ENGINE_VERSION is a hash of every source file that goes
// into the bundle, so any engine change (which can change every seeded result) gives a new
// version and the API re-verifies stored entries.
//
// Usage: pnpm build:verify            (then pnpm sync:verify to copy it into ../SkyShards-API)

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(repoRoot, "src/leaderboard/verify-entry.ts");
const outDir = resolve(repoRoot, "dist-verify");
const outFile = resolve(outDir, "verify.mjs");

// First pass: discover the inputs (metafile) so the version hashes exactly what is bundled.
const probe = await build({
  entryPoints: [entry],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  write: false,
  metafile: true,
  logLevel: "silent",
  define: { __ENGINE_VERSION__: '"probe"' },
});
const inputs = Object.keys(probe.metafile.inputs).sort();
const hash = createHash("sha256");
for (const file of inputs) {
  hash.update(file);
  hash.update("\0");
  hash.update(readFileSync(resolve(repoRoot, file)));
  hash.update("\0");
}
const engineVersion = hash.digest("hex").slice(0, 16);

const result = await build({
  entryPoints: [entry],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: outFile,
  minify: false,
  sourcemap: false,
  legalComments: "none",
  logLevel: "warning",
  define: { __ENGINE_VERSION__: JSON.stringify(engineVersion) },
  banner: {
    js: `#!/usr/bin/env node\n// SkyShards greenhouse flow verifier. Generated by scripts/build-verify.mjs; do not edit.\n// Engine version ${engineVersion} (${new Date().toISOString()}).`,
  },
});
if (result.errors.length) process.exit(1);

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "ENGINE_VERSION"), engineVersion + "\n");
const size = readFileSync(outFile).length;
console.log(`build-verify: ${relative(repoRoot, outFile)} (${(size / 1024).toFixed(0)} KB, ${inputs.length} inputs, engine ${engineVersion})`);
